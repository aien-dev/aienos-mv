//! Documentation backend (Markdown page) and the Omegese form.

use crate::contract::{Access, Contract, Policy, Step, Val};
use std::fmt::Write as _;

fn step_text(s: &Step) -> String {
    match s {
        Step::Write { reg, val } => format!(
            "write {reg} = {}",
            match val {
                Val::Num(n) => format!("{n:#x}"),
                Val::Bits(b) => b.join("|"),
                Val::Var(v) => v.clone(),
            }
        ),
        Step::Poll {
            reg,
            eq,
            tries,
            err,
            ..
        } => format!("poll {reg} until {eq} (at most {tries} reads), else {err}"),
        Step::ArmFail => "from here a failure marks the device FAILED".into(),
        Step::Negotiate => "negotiate features (table above)".into(),
        Step::Expect { lhs, cond, err } => format!("check {lhs} {cond:?}, else {err}"),
        Step::CommitFeatures => "accepted features become active".into(),
        Step::Queues(r) => format!("set up rings {} (qsetup below)", r.join(", ")),
        Step::StableRead {
            reg,
            guard,
            tries,
            err,
            when,
            ..
        } => format!(
            "read {reg} while {guard} holds still (at most {tries} tries), else {err}{}",
            when.as_ref()
                .map(|f| format!(", only when {f} is accepted"))
                .unwrap_or_default()
        ),
        Step::Post(r) => format!("post every {r} buffer"),
        Step::Live => "device is live".into(),
        Step::Kick(r) => format!("ring the {r} doorbell"),
        Step::Read { reg, var } => format!("read {reg} as {var}"),
        Step::Fit { var, min, err } => {
            format!("halve the wanted size until it fits {var}; below {min}: {err}")
        }
        Step::NotifyOffset { reg, err } => {
            format!("doorbell offset = {reg} x multiplier, inside the notify window, else {err}")
        }
        Step::Write64 { lo, hi, what } => format!("write the {what} ring bus address to {lo}/{hi}"),
        Step::AvailFlags(f) => format!("avail flags = {f}"),
    }
}

pub fn markdown(c: &Contract, digest: &str, driver_lines: usize, step_lines: usize) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "<!-- GENERATED by aienos-devc from {} (ADR 0021). Do not edit. -->\n# {} device contract\n",
        c.source_name, c.device
    );
    let proven = c.hardware_receipts();
    let _ = writeln!(
        o,
        "Contract digest `{digest}`. Class `{}`, transport `{}`, ring kind `{}`.\n\nProof status: **{}** ({} hardware receipt(s)); an UNPROVEN driver is admitted for attended boots only.\n",
        c.class,
        c.transport,
        c.ring_kind,
        if proven > 0 { "PROVEN" } else { "UNPROVEN" },
        proven
    );
    o += "## Binds\n\n";
    for m in &c.matches {
        let _ = writeln!(
            o,
            "- PCI {:04x}:{:04x}{}",
            m.vendor,
            m.device,
            m.subsys
                .map(|s| format!(" subsystem {s}"))
                .unwrap_or_default()
        );
    }
    o += "\n## Resources the kernel grants (and nothing else)\n\n| resource | value |\n| --- | --- |\n";
    for w in &c.windows {
        let _ = writeln!(
            o,
            "| MMIO window `{}` | virtio cap type {}, at least {:#x} bytes |",
            w.name, w.cap_type, w.min
        );
    }
    let _ = writeln!(
        o,
        "| DMA | one region, {}-byte aligned, rings and buffers inside it |",
        c.dma_align
    );
    let _ = writeln!(o, "| interrupt | {} (polled) |\n", c.irq);
    o += "## Registers\n\n| window | register | offset | width | access | reset | banked by | role |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n";
    for r in &c.regs {
        let _ = writeln!(
            o,
            "| {} | {}{} | {:#04x} | {} | {} | {} | {} | {} |",
            r.window,
            r.name,
            if r.count > 1 {
                format!("[{}]", r.count)
            } else {
                String::new()
            },
            r.offset,
            r.width,
            match r.access {
                Access::Ro => "ro",
                Access::Rw => "rw",
                Access::Wo => "wo",
            },
            r.reset
                .map(|v| format!("{v:#x}"))
                .unwrap_or_else(|| "-".into()),
            r.bank.clone().unwrap_or_else(|| "-".into()),
            r.role.clone().unwrap_or_else(|| if r.queue_notify {
                "doorbell".into()
            } else {
                "-".into()
            })
        );
    }
    o += "\n## Features\n\n| feature | bit | policy |\n| --- | --- | --- |\n";
    for f in &c.features {
        let mut pol = match f.policy {
            Policy::Require => format!("required, else {}", f.else_err.as_deref().unwrap_or("")),
            Policy::Accept => "accepted when offered".into(),
        };
        if let Some(fl) = &f.required_by {
            let _ = write!(
                pol,
                "; required with flag {fl}, else {}",
                f.else_err.as_deref().unwrap_or("")
            );
        }
        if let Some((w, n)) = &f.needs {
            let _ = write!(pol, "; needs {w} window >= {n} bytes");
        }
        let _ = writeln!(o, "| {} | {} | {pol} |", f.name, f.bit);
    }
    o += "\nEvery other feature bit is declined.\n\n## Bring-up\n\n";
    for (i, s) in c.init.iter().enumerate() {
        let _ = writeln!(o, "{}. {}", i + 1, step_text(s));
    }
    o += "\nPer ring (qsetup):\n\n";
    for (i, s) in c.qsetup.iter().enumerate() {
        let _ = writeln!(o, "{}. {}", i + 1, step_text(s));
    }
    o += "\n## Protocol rules the chip model enforces\n\n";
    for r in &c.rules {
        let _ = writeln!(
            o,
            "- {} {}: status must have {}{}",
            if r.write { "write" } else { "read" },
            r.reg,
            r.requires.join("|"),
            if r.lacks.is_empty() {
                String::new()
            } else {
                format!(" and lack {}", r.lacks.join("|"))
            }
        );
    }
    o += "\n## Errors\n\n| code | name |\n| --- | --- |\n| 0 | Ok |\n";
    for e in &c.errors {
        let _ = writeln!(o, "| {} | {} |", e.code, e.text);
    }
    o += "\n## Evidence\n\n";
    for m in &c.manuals {
        let _ = writeln!(o, "- {}, {}: \"{}\"", m.doc, m.section, m.quote);
    }
    for p in &c.proven {
        let _ = writeln!(
            o,
            "- proven: platform {} machine {} on {} gates {} at {}",
            p.platform,
            p.machine,
            p.date,
            p.gates.join(","),
            p.commit
        );
    }
    let _ = writeln!(
        o,
        "\n## Size\n\n{} contract statements; generated driver {driver_lines} lines, of which {step_lines} compiled from the contract's bring-up steps and the rest from the class `{}` and ring-kind `{}` templates. Hand logic in this contract: 0 lines.",
        c.stmt_count, c.class, c.ring_kind
    );
    o
}

/// The Omegese form of the bring-up. UNCHECKED: Omegese has no machine
/// memory words yet (L184 rung K2 peek/poke) and no units (K5); the words
/// `peek`/`poke` below follow the K2 plan and `win_<name>` is the window
/// base the kernel grants. Kept so the move to Omegese is a translation,
/// not a rewrite.
pub fn omegese(c: &Contract) -> String {
    let mut o = format!(
        "# GENERATED by aienos-devc from {} (ADR 0021). Omegese form, UNCHECKED:\n# needs L184 K2 (peek/poke) and K5 (units). Not compiled today.\n",
        c.source_name
    );
    let up = |n: &str| n.to_string();
    let _ = writeln!(o, "unit {}", c.device.replace('-', "_"));
    for k in &c.consts {
        let _ = writeln!(o, "const {} ulong {}", k.name, k.value);
    }
    for r in &c.regs {
        let _ = writeln!(
            o,
            "reg {} win_{} {} {}",
            r.name, r.window, r.offset, r.width
        );
    }
    let _ = writeln!(o, "fn init (flags uint) to uint");
    for s in &c.init {
        let line = match s {
            Step::Write { reg, val } => format!(
                "poke{} win_{} {} {}",
                c.reg(reg).map(|r| r.width * 8).unwrap_or(32),
                c.reg(reg).map(|r| r.window.as_str()).unwrap_or("?"),
                c.reg(reg).map(|r| r.offset).unwrap_or(0),
                match val {
                    Val::Num(n) => n.to_string(),
                    Val::Bits(b) => b.iter().map(|x| up(x)).collect::<Vec<_>>().join(" or "),
                    Val::Var(v) => v.clone(),
                }
            ),
            Step::Poll {
                reg,
                eq,
                tries,
                err,
                ..
            } => format!(
                "while ne peek{} win_{} {} {eq} bound {tries}\nend   # past the bound: ret {err}",
                c.reg(reg).map(|r| r.width * 8).unwrap_or(32),
                c.reg(reg).map(|r| r.window.as_str()).unwrap_or("?"),
                c.reg(reg).map(|r| r.offset).unwrap_or(0)
            ),
            other => format!("# {}", step_text(other)),
        };
        for l in line.lines() {
            let _ = writeln!(o, "  {l}");
        }
    }
    o += "  ret 0\nend\n";
    o
}
