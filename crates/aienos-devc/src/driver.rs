//! Driver backend: class net-poll over transport virtio-pci with ring kind
//! virtq-split. Emits a header source-compatible with the hand-written
//! reference (same names, same struct fields, same API) and the driver C.
//!
//! The only device access in the emitted C is one accessor per declared
//! register (`rd_<REG>` for readable, `wr_<REG>` for writable, `nt_<REG>` for
//! the doorbell), each with its window, offset and width fixed at generation
//! time. Steps compile to calls of those accessors; there is no accessor for
//! an undeclared register, so the driver cannot reach one.

use crate::contract::{Access, Cond, Contract, Dir, Policy, Reg, Step, Val};
use std::fmt::Write as _;

pub fn banner(c: &Contract, comment_open: &str, comment_close: &str) -> String {
    format!(
        "{comment_open} GENERATED by aienos-devc from {} (device contract, ADR 0021). Do not edit:\n * edit the contract and run `make -C native/net contract-gen`. {comment_close}\n",
        c.source_name
    )
}

fn win_cname(c: &Contract, w: &str) -> String {
    format!("{}_WIN_{}", c.up(), w.to_uppercase())
}

/// virtio-pci: capability type -> field of virtio_pci_caps
fn cap_field(cap_type: u32) -> &'static str {
    match cap_type {
        1 => "common_cfg",
        2 => "notify_cfg",
        3 => "isr_cfg",
        _ => "device_cfg",
    }
}

fn mask_of(r: &Reg) -> String {
    match r.width {
        1 => "0xffu".into(),
        2 => "0xffffu".into(),
        _ => "0xffffffffu".into(),
    }
}

pub fn header(c: &Contract) -> String {
    let p = &c.prefix;
    let up = c.up();
    let mut h = String::new();
    h += &banner(c, "/*", "*/");
    let _ = writeln!(
        h,
        "/* {} driver, class {}, transport {}, ring kind {}: polled, hosted-testable.\n * Device access goes through {p}_ops only. All rings and buffers live in ONE\n * caller-provided region the device sees at bus address `dma`. Anything the\n * device writes is untrusted; a hostile completion marks the device broken\n * (sticky). Resources: {} register windows, one DMA region, irq {}. */",
        c.device,
        c.class,
        c.transport,
        c.ring_kind,
        c.windows.len(),
        c.irq
    );
    h += "#ifndef AIENOS_VIRTIO_NET_H\n#define AIENOS_VIRTIO_NET_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n#include \"aienos_virtio_pci.h\"\n\n";
    h += "/* constants */\n";
    for k in &c.consts {
        let _ = writeln!(h, "#define {up}_{} {}", k.name, k.c_expr);
    }
    h += "\n/* features (offered bits the driver may accept; all others are declined) */\n";
    for f in &c.features {
        let _ = writeln!(h, "#define {up}_F_{} {}u", f.name, f.bit);
    }
    h += "\n/* init flags */\n";
    for (n, v) in &c.flags {
        let _ = writeln!(h, "#define {up}_INIT_{n} {v}u");
    }
    for w in &c.windows {
        let _ = writeln!(
            h,
            "\n/* window {} (virtio cap type {}), byte offsets */",
            w.name, w.cap_type
        );
        for r in c.regs.iter().filter(|r| r.window == w.name) {
            let _ = writeln!(h, "#define {} 0x{:02x}u", c.reg_cname(r), r.offset);
        }
        if let (Some(t), true) = (&w.tag, w.min > 0) {
            let _ = writeln!(h, "#define {up}_{t}_LEN 0x{:02x}u", w.min);
        }
    }
    for b in &c.bits {
        let _ = writeln!(h, "\n/* {} bits */", b.reg);
        for (n, v) in &b.bits {
            let _ = writeln!(h, "#define {up}_{}_{n} {}u", b.group, 1u64 << v);
        }
    }
    h += "\n/* ring kind virtq-split (virtio 1.x 2.7) */\n";
    let _ = writeln!(
        h,
        "#define {up}_DESC_F_WRITE 2u\n#define {up}_AVAIL_F_NO_INTERRUPT 1u\n"
    );
    h += "enum { ";
    h += &c
        .rings
        .iter()
        .map(|r| format!("{up}_{}_QUEUE = {}", r.name, r.index))
        .collect::<Vec<_>>()
        .join(", ");
    h += " };\ntypedef enum { ";
    h += &c
        .windows
        .iter()
        .map(|w| format!("{} = {}", win_cname(c, &w.name), w.index))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(h, " }} {p}_window;\n");
    let _ = write!(
        h,
        "typedef struct {{
    void *ctx;
    /* width is 1, 2 or 4; off + width is already checked against the window */
    uint32_t (*read)(void *ctx, {p}_window win, uint32_t off, unsigned width);
    void (*write)(void *ctx, {p}_window win, uint32_t off, unsigned width, uint32_t val);
    /* write `queue` (16 bit) at byte `off` of the notify window (checked) */
    void (*notify)(void *ctx, uint32_t off, uint16_t queue);
}} {p}_ops;

typedef enum {{
    {up}_OK = 0,
"
    );
    for e in &c.errors {
        let _ = writeln!(h, "    {up}_E_{} = {},", e.name, e.code);
    }
    let qmax = c.cname(&c.qsize_max);
    let _ = write!(
        h,
        "}} {p}_err;

typedef struct {{
    uint16_t size;          /* negotiated, power of two, <= {qmax} */
    uint16_t avail_idx;     /* driver shadow of avail->idx */
    uint16_t last_used;     /* next used-ring slot to consume */
    uint16_t in_flight;     /* descriptors posted and not yet completed */
    uint32_t notify_off;    /* byte offset in the notify window */
    size_t desc_off, avail_off, used_off, buf_off; /* offsets into mem */
    uint8_t posted[{qmax}];
}} {p}_queue;

typedef struct {{
    {p}_ops ops;
    virtio_pci_caps caps;
    uint8_t *mem;
    uint64_t dma;
    size_t mem_len;
    uint64_t features;      /* accepted feature bits */
    uint8_t has_mac;
    uint8_t mac[6];
    uint8_t broken;
    {p}_queue q[{nq}];
}} {p}_dev;

/* Contract identity and proof status (ADR 0021 \"Evidence\"): the kernel admits
 * an UNPROVEN driver for attended boots only. */
#define {up}_CONTRACT_DEVICE \"{dev}\"
#define {up}_CONTRACT_PROVEN {proven}
extern const char {p}_contract_digest[65];

size_t {p}_mem_size(uint16_t qsize);
{p}_err {p}_init({p}_dev *d, const {p}_ops *ops, const virtio_pci_caps *caps,
                   void *mem, uint64_t dma, size_t mem_len, uint16_t qsize);
{p}_err {p}_init_flags({p}_dev *d, const {p}_ops *ops, const virtio_pci_caps *caps, void *mem, uint64_t dma,
                         size_t mem_len, uint16_t qsize, uint32_t flags);
{p}_err {p}_tx({p}_dev *d, const uint8_t *frame, size_t len);
{p}_err {p}_tx_reclaim({p}_dev *d, unsigned *reclaimed);
{p}_err {p}_rx({p}_dev *d, uint8_t *out, size_t cap, size_t *len, int *got);
const char *{p}_err_name({p}_err e);

#endif
",
        nq = c.rings.len(),
        dev = c.device,
        proven = c.hardware_receipts(),
    );
    h
}

/// The value of a write step as C.
fn val_c(c: &Contract, reg: &str, v: &Val) -> String {
    match v {
        Val::Num(n) if *n > 9 => format!("0x{n:x}u"),
        Val::Num(n) => format!("{n}"),
        Val::Bits(b) => b
            .iter()
            .map(|x| c.bit_cname(reg, x))
            .collect::<Vec<_>>()
            .join(" | "),
        Val::Var(v) if v == "ring" => "index".into(),
        Val::Var(_) => "n".into(),
    }
}

fn bits_mask(c: &Contract, reg: &str, b: &[String]) -> String {
    let m = b
        .iter()
        .map(|x| c.bit_cname(reg, x))
        .collect::<Vec<_>>()
        .join(" | ");
    if b.len() > 1 {
        format!("({m})")
    } else {
        m
    }
}

/// Compile one step. `armed`: errors go through fail(). `q`: inside setup_queue.
fn step_c(c: &Contract, s: &Step, armed: bool, q: bool, o: &mut String) {
    let up = c.up();
    let ret = |e: &str, nofail: bool| -> String {
        if armed && !nofail && !q {
            format!("return fail(d, {up}_E_{e});")
        } else {
            format!("return {up}_E_{e};")
        }
    };
    match s {
        Step::Write { reg, val } => {
            let _ = writeln!(o, "    wr_{reg}(d, {});", val_c(c, reg, val));
        }
        Step::Poll {
            reg,
            eq,
            tries,
            err,
            nofail,
        } => {
            let _ = writeln!(
                o,
                "    {{\n        unsigned polls = 0;\n        while (rd_{reg}(d) != {eq})\n            if (++polls >= {}) {}\n    }}",
                c.cname(tries),
                ret(err, *nofail)
            );
        }
        Step::ArmFail => {}
        Step::Negotiate => {
            let fb = c.feature_banks.as_ref().expect("checked");
            let (os, of, as_, af) = (&fb.offer_sel, &fb.offer, &fb.accept_sel, &fb.accept);
            let _ = writeln!(o, "    /* features: read the offer, refuse what is required and missing, accept the declared subset */");
            let _ = writeln!(o, "    wr_{os}(d, 0);\n    uint64_t offered = rd_{of}(d);\n    wr_{os}(d, 1);\n    offered |= (uint64_t)rd_{of}(d) << 32;");
            for f in c.features.iter().filter(|f| f.policy == Policy::Require) {
                let _ = writeln!(
                    o,
                    "    if (!(offered >> {up}_F_{} & 1)) {}",
                    f.name,
                    ret(f.else_err.as_ref().unwrap(), false)
                );
            }
            for f in c.features.iter().filter(|f| f.required_by.is_some()) {
                let _ = writeln!(
                    o,
                    "    if ((flags & {up}_INIT_{}) && !(offered >> {up}_F_{} & 1)) {}",
                    f.required_by.as_ref().unwrap(),
                    f.name,
                    ret(f.else_err.as_ref().unwrap(), false)
                );
            }
            let req: Vec<String> = c
                .features
                .iter()
                .filter(|f| f.policy == Policy::Require)
                .map(|f| format!("(1ull << {up}_F_{})", f.name))
                .collect();
            let acc: Vec<String> = c
                .features
                .iter()
                .filter(|f| f.policy == Policy::Accept)
                .map(|f| format!("(1ull << {up}_F_{})", f.name))
                .collect();
            let _ = writeln!(
                o,
                "    uint64_t accept = {} | (offered & ({}));",
                req.join(" | "),
                acc.join(" | ")
            );
            for f in c.features.iter().filter(|f| f.needs.is_some()) {
                let (w, len) = f.needs.as_ref().unwrap();
                let field = cap_field(c.window(w).unwrap().cap_type);
                let _ = writeln!(
                    o,
                    "    if ((accept >> {up}_F_{} & 1) && caps->{field}.length < {len}) {}",
                    f.name,
                    ret("CAPS", false)
                );
            }
            let _ = writeln!(o, "    wr_{as_}(d, 0);\n    wr_{af}(d, (uint32_t)accept);\n    wr_{as_}(d, 1);\n    wr_{af}(d, (uint32_t)(accept >> 32));");
        }
        Step::Expect { lhs, cond, err } => {
            let lv = if c.reg(lhs).is_some() {
                format!("rd_{lhs}(d)")
            } else {
                lhs.clone()
            };
            let test = match cond {
                Cond::Has(h, l) if l.is_empty() => format!("!({lv} & {})", bits_mask(c, lhs, h)),
                Cond::Has(h, l) => {
                    let _ = writeln!(o, "    {{\n        uint32_t v = {lv};");
                    let _ = writeln!(
                        o,
                        "        if ((v & {}) || (v & {hm}) != {hm}) {}\n    }}",
                        bits_mask(c, lhs, l),
                        ret(err, false),
                        hm = bits_mask(c, lhs, h)
                    );
                    return;
                }
                Cond::Ge(n) => format!("{lv} < {n}"),
                Cond::Ne(n) => format!("{lv} == {n}"),
                Cond::Eq(n) => format!("{lv} != {n}"),
            };
            let _ = writeln!(o, "    if ({test}) {}", ret(err, false));
        }
        Step::CommitFeatures => {
            let _ = writeln!(o, "    d->features = accept;");
        }
        Step::Queues(rs) => {
            let _ = writeln!(
                o,
                "    {{\n        static const uint16_t order[{}] = {{{}}};",
                rs.len(),
                rs.iter()
                    .map(|r| format!("{up}_{r}_QUEUE"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            let _ = writeln!(
                o,
                "        for (unsigned i = 0; i < {}; i++) {{\n            {p}_err e = setup_queue(d, order[i], qsize);\n            if (e) return fail(d, e);\n        }}\n    }}",
                rs.len(),
                p = c.prefix
            );
        }
        Step::StableRead {
            reg,
            guard,
            tries,
            err,
            when,
            ..
        } => {
            let r = c.reg(reg).unwrap();
            let cond = match when {
                Some(f) => format!("accept >> {up}_F_{f} & 1"),
                None => "1".into(),
            };
            let _ = writeln!(
                o,
                "    if ({cond}) {{\n        unsigned t = 0;\n        for (;; t++) {{\n            if (t >= {}) {}\n            uint32_t g0 = rd_{guard}(d);\n            for (uint32_t i = 0; i < {}; i++) d->mac[i] = (uint8_t)rd_{reg}(d, i);\n            if (rd_{guard}(d) == g0) break;\n        }}\n        d->has_mac = 1;\n    }}",
                c.cname(tries),
                ret(err, false),
                r.count
            );
        }
        Step::Post(r) => {
            let ring = c.ring(r).unwrap();
            let flag = if ring.dir == Dir::DeviceWrites {
                format!("{up}_DESC_F_WRITE")
            } else {
                "0".into()
            };
            let _ = writeln!(
                o,
                "    {{\n        {p}_queue *pq = &d->q[{up}_{r}_QUEUE];\n        for (uint16_t id = 0; id < pq->size; id++) {{\n            if (!set_desc(d, pq, id, {}, {flag})) {}\n            avail_push(d, pq, id);\n        }}\n    }}",
                c.cname(&ring.buf),
                ret("MEM", false),
                p = c.prefix
            );
        }
        Step::Live => {
            let _ = writeln!(o, "    d->broken = 0;");
        }
        Step::Kick(r) => {
            let _ = writeln!(o, "    kick(d, &d->q[{up}_{r}_QUEUE], {up}_{r}_QUEUE);");
        }
        Step::Read { reg, var } => {
            let _ = writeln!(o, "    uint32_t {var} = rd_{reg}(d);");
        }
        Step::Fit { var, min, err } => {
            let _ = writeln!(
                o,
                "    uint32_t n = want;\n    while (n > {var}) n >>= 1;\n    if (n < {}) {}\n    q->size = (uint16_t)n;",
                c.cname(min),
                ret(err, false)
            );
        }
        Step::NotifyOffset { reg, err } => {
            let db = c.doorbell();
            let wf = cap_field(c.window(&db.window).unwrap().cap_type);
            let _ = writeln!(
                o,
                "    uint64_t noff = (uint64_t)rd_{reg}(d) * d->caps.notify_off_multiplier;\n    if (noff + {} > d->caps.{wf}.length) {}\n    q->notify_off = (uint32_t)noff;",
                db.width,
                ret(err, false)
            );
        }
        Step::Write64 { lo, hi, what } => {
            let _ = writeln!(
                o,
                "    wr_{lo}(d, (uint32_t)(d->dma + q->{what}_off));\n    wr_{hi}(d, (uint32_t)((d->dma + q->{what}_off) >> 32));"
            );
        }
        Step::AvailFlags(f) => {
            let _ = writeln!(o, "    put16(d->mem + q->avail_off, {up}_AVAIL_F_{f});");
        }
    }
}

pub fn source(c: &Contract, digest: &str) -> String {
    let p = &c.prefix;
    let up = c.up();
    let mut o = String::new();
    o += &banner(c, "/*", "*/");
    o += "#include \"aienos_virtio_net.h\"\n\n#include <string.h>\n\n";
    o += "#if !defined(__BYTE_ORDER__) || __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__\n#error \"virtio 1.x rings are little-endian; this driver assumes a little-endian CPU\"\n#endif\n\n";
    let _ = writeln!(o, "const char {p}_contract_digest[65] = \"{digest}\";\n");
    o += "#define ALIGN_UP(x, a) (((x) + ((a) - 1)) & ~(size_t)((a) - 1))\n\n";
    // error names
    let _ = writeln!(o, "const char *{p}_err_name({p}_err e)\n{{\n    switch (e) {{\n    case {up}_OK: return \"Ok\";");
    for e in &c.errors {
        let _ = writeln!(o, "    case {up}_E_{}: return \"{}\";", e.name, e.text);
    }
    o += "    }\n    return \"Unknown\";\n}\n\n";
    let (qmin, qmax) = (c.cname(&c.qsize_min), c.cname(&c.qsize_max));
    let stride = c.cname(&c.rx_ring().stride);
    let _ = write!(
        o,
        "static int pow2_ok(uint32_t n) {{ return n >= {qmin} && n <= {qmax} && (n & (n - 1)) == 0; }}

/* virtq-split layout of one queue sized for qsize, starting at base; returns the end. */
static size_t queue_layout({p}_queue *q, size_t base, uint32_t qsize)
{{
    size_t at = ALIGN_UP(base, 64);
    q->desc_off = at;  at += 16u * qsize;
    at = ALIGN_UP(at, 64);
    q->avail_off = at; at += 6u + 2u * qsize;
    at = ALIGN_UP(at, 64);
    q->used_off = at;  at += 6u + 8u * qsize;
    at = ALIGN_UP(at, 64);
    q->buf_off = at;   at += (size_t){stride} * qsize;
    return at;
}}

size_t {p}_mem_size(uint16_t qsize)
{{
    if (!pow2_ok(qsize)) return 0;
    {p}_queue q;
    return {nest};
}}

/* ---- register access, bounded by the parsed capability windows ---- */
static const virtio_pci_region *win_region(const {p}_dev *d, {p}_window w)
{{
    switch (w) {{
",
        nest = (0..c.rings.len()).fold("0".to_string(), |acc, _| format!("queue_layout(&q, {acc}, qsize)")),
    );
    for w in &c.windows {
        let _ = writeln!(
            o,
            "    case {}: return &d->caps.{};",
            win_cname(c, &w.name),
            cap_field(w.cap_type)
        );
    }
    let _ = write!(
        o,
        "    }}
    return NULL;
}}
static int win_ok(const {p}_dev *d, {p}_window w, uint32_t off, unsigned width)
{{
    const virtio_pci_region *r = win_region(d, w);
    return r && r->present && (uint64_t)off + width <= r->length;
}}
static uint32_t rd({p}_dev *d, {p}_window w, uint32_t off, unsigned width)
{{
    if (!win_ok(d, w, off, width)) return 0;
    return d->ops.read(d->ops.ctx, w, off, width);
}}
static void wr({p}_dev *d, {p}_window w, uint32_t off, unsigned width, uint32_t v)
{{
    if (win_ok(d, w, off, width)) d->ops.write(d->ops.ctx, w, off, width, v);
}}

/* ---- one accessor per declared register: the driver's whole device reach ---- */
"
    );
    for r in &c.regs {
        let wc = win_cname(c, &r.window);
        let off = c.reg_cname(r);
        if r.queue_notify {
            let _ = writeln!(
                o,
                "static void nt_{}({p}_dev *d, uint32_t off, uint16_t queue) {{ d->ops.notify(d->ops.ctx, off, queue); }}",
                r.name
            );
            continue;
        }
        let (idx_param, idx_off) = if r.count > 1 {
            (
                ", uint32_t i".to_string(),
                format!(" + (i < {} ? i : 0) * {}u", r.count, r.width),
            )
        } else {
            (String::new(), String::new())
        };
        if r.access != Access::Wo {
            let _ = writeln!(
                o,
                "static inline uint32_t rd_{}({p}_dev *d{idx_param}) {{ return rd(d, {wc}, {off}{idx_off}, {}); }}",
                r.name, r.width
            );
        }
        if r.access != Access::Ro {
            let _ = writeln!(
                o,
                "static inline void wr_{}({p}_dev *d{idx_param}, uint32_t v) {{ wr(d, {wc}, {off}{idx_off}, {}, v & {}); }}",
                r.name,
                r.width,
                mask_of(r)
            );
        }
    }
    let db = c.doorbell();
    let (fr, fbit) = c.failmark.as_ref().unwrap();
    let rx = c.rx_ring();
    let tx = c.tx_ring();
    let (rxb, txb) = (c.cname(&rx.buf), c.cname(&tx.buf));
    let (rxh, txh) = (c.cname(&rx.hdr), c.cname(&tx.hdr));
    let rx_stride = c.cname(&rx.stride);
    let tx_stride = c.cname(&tx.stride);
    let frame_max = c.cname("FRAME_MAX");
    let _ = write!(
        o,
        "
/* ---- shared ring memory (virtq-split) ---- */
static int in_region(const {p}_dev *d, size_t off, size_t len)
{{
    return off <= d->mem_len && len <= d->mem_len - off;
}}
static void put16(uint8_t *p, uint16_t v) {{ memcpy(p, &v, 2); }}
static void put32(uint8_t *p, uint32_t v) {{ memcpy(p, &v, 4); }}
static void put64(uint8_t *p, uint64_t v) {{ memcpy(p, &v, 8); }}

/* Write descriptor `id` of queue q for its own buffer; 0 when it would leave the region. */
static int set_desc({p}_dev *d, {p}_queue *q, uint16_t id, uint32_t len, uint16_t flags)
{{
    size_t boff = q->buf_off + (size_t)id * {rx_stride};
    if (id >= q->size || len > {rxb} || !in_region(d, boff, len)) return 0;
    uint8_t *e = d->mem + q->desc_off + 16u * id;
    put64(e, d->dma + boff);
    put32(e + 8, len);
    put16(e + 12, flags);
    put16(e + 14, 0);
    return 1;
}}

static void avail_push({p}_dev *d, {p}_queue *q, uint16_t id)
{{
    uint8_t *a = d->mem + q->avail_off;
    put16(a + 4 + 2u * (q->avail_idx & (q->size - 1)), id);
    q->avail_idx++;
    q->posted[id] = 1;
    q->in_flight++;
    __atomic_thread_fence(__ATOMIC_RELEASE); /* ring entry before idx */
    __atomic_store_n((uint16_t *)(void *)(a + 2), q->avail_idx, __ATOMIC_RELEASE);
}}

static void kick({p}_dev *d, {p}_queue *q, uint16_t index)
{{
    __atomic_thread_fence(__ATOMIC_SEQ_CST); /* idx visible before the notify */
    nt_{dbn}(d, q->notify_off, index);
}}

static {p}_err mark_broken({p}_dev *d)
{{
    d->broken = 1;
    return {up}_E_DEVICE;
}}

/* Take the next used entry, validating everything the device wrote. */
static {p}_err used_next({p}_dev *d, {p}_queue *q, uint32_t limit, uint16_t *id_out, uint32_t *len_out, int *got)
{{
    *got = 0;
    uint8_t *u = d->mem + q->used_off;
    uint16_t idx = __atomic_load_n((uint16_t *)(void *)(u + 2), __ATOMIC_ACQUIRE);
    uint16_t pending = (uint16_t)(idx - q->last_used);
    if (pending == 0) return {up}_OK;
    if (pending > q->in_flight) return mark_broken(d);
    const volatile uint8_t *e = u + 4 + 8u * (q->last_used & (q->size - 1));
    uint32_t id = 0, len = 0;
    for (int i = 0; i < 4; i++) {{ id |= (uint32_t)e[i] << (8 * i); len |= (uint32_t)e[4 + i] << (8 * i); }}
    if (id >= q->size || !q->posted[id] || len > limit) return mark_broken(d);
    q->posted[id] = 0;
    q->in_flight--;
    q->last_used++;
    *id_out = (uint16_t)id;
    *len_out = len;
    *got = 1;
    return {up}_OK;
}}

/* failmark: {fr} |= {fbit} */
static {p}_err fail({p}_dev *d, {p}_err e)
{{
    uint32_t s = rd_{fr}(d);
    wr_{fr}(d, (s | {fbitc}) & {fmask});
    return e;
}}

/* qsetup, once per ring in `queues` order */
static {p}_err setup_queue({p}_dev *d, uint16_t index, uint32_t want)
{{
    {p}_queue *q = &d->q[index];
",
        dbn = db.name,
        fbitc = c.bit_cname(fr, fbit),
        fmask = mask_of(c.reg(fr).unwrap()),
    );
    for s in &c.qsetup {
        step_c(c, s, false, true, &mut o);
    }
    let _ = write!(
        o,
        "    return {up}_OK;
}}

{p}_err {p}_init({p}_dev *d, const {p}_ops *ops, const virtio_pci_caps *caps,
                   void *mem, uint64_t dma, size_t mem_len, uint16_t qsize)
{{
    return {p}_init_flags(d, ops, caps, mem, dma, mem_len, qsize, 0);
}}

{p}_err {p}_init_flags({p}_dev *d, const {p}_ops *ops, const virtio_pci_caps *caps, void *mem, uint64_t dma,
                         size_t mem_len, uint16_t qsize, uint32_t flags)
{{
    if (!d) return {up}_E_ARG;
    memset(d, 0, sizeof *d);
    d->broken = 1; /* until init succeeds */
    if ((flags & ~({allflags})) || !ops || !ops->read || !ops->write || !ops->notify || !caps ||
        !mem || !pow2_ok(qsize))
        return {up}_E_ARG;
    /* every declared window present and at least its declared length */
    if (",
        allflags = if c.flags.is_empty() {
            "0u".to_string()
        } else {
            c.flags.iter().map(|(n, _)| format!("{up}_INIT_{n}")).collect::<Vec<_>>().join(" | ")
        },
    );
    let mut wc = Vec::new();
    for w in &c.windows {
        let f = cap_field(w.cap_type);
        wc.push(format!("!caps->{f}.present"));
        if w.multiplier {
            wc.push("!caps->has_notify_off_multiplier".into());
        }
        if w.min > 0 {
            let lim = match &w.tag {
                Some(t) => format!("{up}_{t}_LEN"),
                None => format!("{}", w.min),
            };
            wc.push(format!("caps->{f}.length < {lim}"));
        }
    }
    o += &wc.join(" ||\n        ");
    let align = c.dma_align - 1;
    let _ = write!(
        o,
        ")
        return {up}_E_CAPS;
    size_t need = {p}_mem_size(qsize);
    if (mem_len < need || ((uintptr_t)mem & {align}u) || (dma & {align}u) || dma > UINT64_MAX - mem_len)
        return {up}_E_MEM;
    d->ops = *ops;
    d->caps = *caps;
    d->mem = mem;
    d->dma = dma;
    d->mem_len = mem_len;
    memset(mem, 0, need);
"
    );
    let _ = writeln!(o, "    size_t end = 0;");
    for r in &c.rings {
        let _ = writeln!(
            o,
            "    end = queue_layout(&d->q[{up}_{}_QUEUE], end, qsize);",
            r.name
        );
    }
    let _ = writeln!(o, "    (void)end;\n");
    let mut armed = false;
    for s in &c.init {
        if matches!(s, Step::ArmFail) {
            armed = true;
            let _ = writeln!(
                o,
                "    /* armfail: from here a failed step marks {fr} {fbit} */"
            );
            continue;
        }
        step_c(c, s, armed, false, &mut o);
    }
    let _ = write!(
        o,
        "    return {up}_OK;
}}

{p}_err {p}_tx_reclaim({p}_dev *d, unsigned *reclaimed)
{{
    if (reclaimed) *reclaimed = 0;
    if (!d) return {up}_E_ARG;
    if (d->broken) return {up}_E_BROKEN;
    {p}_queue *q = &d->q[{up}_{txn}_QUEUE];
    for (;;) {{
        uint16_t id; uint32_t len; int got;
        /* device-reads buffers: a report above one buffer length is hostile */
        {p}_err e = used_next(d, q, {txb}, &id, &len, &got);
        if (e || !got) return e;
        if (reclaimed) (*reclaimed)++;
    }}
}}

{p}_err {p}_tx({p}_dev *d, const uint8_t *frame, size_t len)
{{
    if (!d || !frame || len < 14 || len > {frame_max}) return {up}_E_ARG;
    if (d->broken) return {up}_E_BROKEN;
    {p}_queue *q = &d->q[{up}_{txn}_QUEUE];
    if (q->in_flight >= q->size) return {up}_E_FULL;
    uint16_t id = 0;
    while (id < q->size && q->posted[id]) id++;
    if (id >= q->size) return {up}_E_FULL;
    if (!set_desc(d, q, id, (uint32_t)({txh} + len), 0)) return {up}_E_MEM;
    uint8_t *b = d->mem + q->buf_off + (size_t)id * {tx_stride};
    memset(b, 0, {txh}); /* zero header: no offloads negotiated */
    memcpy(b + {txh}, frame, len);
    avail_push(d, q, id);
    kick(d, q, {up}_{txn}_QUEUE);
    return {up}_OK;
}}

{p}_err {p}_rx({p}_dev *d, uint8_t *out, size_t cap, size_t *len, int *got)
{{
    if (got) *got = 0;
    if (len) *len = 0;
    if (!d || !out || !len || !got || cap < {frame_max}) return {up}_E_ARG;
    if (d->broken) return {up}_E_BROKEN;
    {p}_queue *q = &d->q[{up}_{rxn}_QUEUE];
    uint16_t id; uint32_t n; int have;
    {p}_err e = used_next(d, q, {rxb}, &id, &n, &have);
    if (e || !have) return e;
    if (n < {rxh}) return mark_broken(d); /* every completion carries the header */
    size_t flen = n - {rxh};
    memcpy(out, d->mem + q->buf_off + (size_t)id * {rx_stride} + {rxh}, flen);
    if (!set_desc(d, q, id, {rxb}, {up}_DESC_F_WRITE)) return mark_broken(d);
    avail_push(d, q, id);
    kick(d, q, {up}_{rxn}_QUEUE);
    *len = flen;
    *got = 1;
    return {up}_OK;
}}
",
        txn = tx.name,
        rxn = rx.name,
    );
    o
}

/// Lines of C one step compiles to (for the size report).
pub fn step_c_lines(c: &Contract, s: &Step, armed: bool, q: bool) -> usize {
    let mut o = String::new();
    step_c(c, s, armed, q, &mut o);
    o.lines().count()
}
